// Check if string contains Tamil characters
export function hasTamilCharacters(str) {
  if (!str) return false;
  return /[\u0B80-\u0BFF]/.test(String(str));
}

// Smart Tamil product translation
export function getTamilProductName(rawName) {
  if (!rawName) return '';
  const trimmed = String(rawName).trim();
  if (!trimmed) return '';

  // If already in Tamil, return as is
  if (hasTamilCharacters(trimmed)) {
    return trimmed;
  }

  const lower = trimmed.toLowerCase();

  // 1. Direct dictionary lookup
  if (PRODUCT_TAMIL_MAP[lower]) {
    return PRODUCT_TAMIL_MAP[lower];
  }

  // 2. Clean punctuation & extra spaces
  const clean = lower.replace(/[_\-+()/,.]/g, ' ').replace(/\s+/g, ' ').trim();
  if (PRODUCT_TAMIL_MAP[clean]) {
    return PRODUCT_TAMIL_MAP[clean];
  }

  // 3. Check compound phrases (e.g., "Tata Salt", "Gold Winner Sunflower Oil 1L")
  const sizeMatch = trimmed.match(/(\d+(?:\.\d+)?\s*(?:kg|g|gm|gms|l|ltr|litre|litres|ml|pcs|pc|nos|no|rs|rupees)?)\s*$/i);
  const sizePart = sizeMatch ? sizeMatch[1] : '';
  const nameWithoutSize = (sizeMatch ? trimmed.slice(0, sizeMatch.index) : trimmed).trim().toLowerCase();

  if (PRODUCT_TAMIL_MAP[nameWithoutSize]) {
    return sizePart ? `${PRODUCT_TAMIL_MAP[nameWithoutSize]} ${sizePart}` : PRODUCT_TAMIL_MAP[nameWithoutSize];
  }

  // Check brand prefix + product suffix (e.g. "Tata Salt" -> "டாடா" + "உப்பு")
  for (const [brand, brandTa] of Object.entries(BRAND_TAMIL_MAP)) {
    if (nameWithoutSize.startsWith(brand)) {
      const rest = nameWithoutSize.slice(brand.length).trim();
      if (rest) {
        const restTa = PRODUCT_TAMIL_MAP[rest] || rest;
        return `${brandTa} ${restTa}${sizePart ? ' ' + sizePart : ''}`.trim();
      }
      return `${brandTa}${sizePart ? ' ' + sizePart : ''}`.trim();
    }
  }

  // Check sub-phrases
  for (const [enKey, taVal] of Object.entries(PRODUCT_TAMIL_MAP)) {
    if (enKey.length >= 4 && nameWithoutSize.includes(enKey)) {
      const replaced = nameWithoutSize.replace(enKey, taVal);
      return `${replaced}${sizePart ? ' ' + sizePart : ''}`.trim();
    }
  }

  // Fallback: return original name
  return trimmed;
}

// Universal getProductName helper
export function getProductName(itemOrName, lang = 'en') {
  if (!itemOrName) return '';

  let name = '';
  let altName = '';

  if (typeof itemOrName === 'string') {
    name = itemOrName;
  } else if (typeof itemOrName === 'object') {
    name = itemOrName.name || '';
    altName = itemOrName.altName || '';
  }

  if (lang !== 'ta') {
    return name || altName || '';
  }

  // If Tamil requested:
  // 1. If explicit altName exists and has Tamil, use it
  if (altName && hasTamilCharacters(altName)) {
    return altName.trim();
  }

  // 2. If name itself has Tamil, use it
  if (name && hasTamilCharacters(name)) {
    return name.trim();
  }

  // 3. Fallback to smart dictionary translation of altName or name
  const sourceName = (altName || name).trim();
  return getTamilProductName(sourceName) || sourceName;
}

